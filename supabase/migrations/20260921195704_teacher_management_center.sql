create or replace function public.get_public_classroom_state()
returns jsonb language sql stable security definer set search_path=''
as $$ select jsonb_build_object(
 'settings',(select jsonb_build_object('activity_name',activity_name,'activity_finalized',activity_finalized) from public.classroom_settings where id=1),
 'announcement',(select jsonb_build_object('title',title,'message',message,'updated_at',updated_at) from public.announcements where deleted_at is null and is_published and (expires_at is null or expires_at>now()) order by is_featured desc,updated_at desc limit 1),
 'groups',(select coalesce(jsonb_agg(jsonb_build_object('id',g.id,'name',g.name,'description',g.description,'status',g.activity_status,'members',(select count(*) from public.profiles p where p.group_id=g.id and p.role='student' and not p.is_anonymous),'recipes',(select count(*) from public.recipes r where r.group_id=g.id and r.deleted_at is null),'check_done',(select count(*) from public.group_checklist c where c.group_id=g.id and (case when c.is_manual then c.is_completed else case c.item_key when 'members_defined' then exists(select 1 from public.profiles p where p.group_id=g.id and p.role='student' and not p.is_anonymous) when 'call_numbers' then not exists(select 1 from public.profiles p where p.group_id=g.id and p.role='student' and not p.is_anonymous and p.call_number is null) and exists(select 1 from public.profiles p where p.group_id=g.id and p.role='student' and not p.is_anonymous) when 'recipe_registered' then exists(select 1 from public.recipes r where r.group_id=g.id and r.deleted_at is null) when 'ingredients_filled' then exists(select 1 from public.recipes r where r.group_id=g.id and r.deleted_at is null and length(btrim(r.ingredients))>0) when 'instructions_filled' then exists(select 1 from public.recipes r where r.group_id=g.id and r.deleted_at is null and length(btrim(r.instructions))>0) when 'recipe_reviewed' then exists(select 1 from public.recipes r where r.group_id=g.id and r.deleted_at is null and r.review_status in ('changes_requested','approved')) when 'teacher_approved' then exists(select 1 from public.recipes r where r.group_id=g.id and r.deleted_at is null and r.review_status='approved') else false end end)),'check_total',(select count(*) from public.group_checklist c where c.group_id=g.id)) order by g.slug),'[]'::jsonb) from public.groups g)
) $$;
revoke all on function public.get_public_classroom_state() from public;
grant execute on function public.get_public_classroom_state() to anon,authenticated;

-- Bloqueio global também é imposto nas escritas do aluno.
create or replace function public.guard_recipe_classroom() returns trigger
language plpgsql security definer set search_path=''
as $$ declare user_role text; group_status text; global_lock boolean; finalized boolean; begin
  select role into user_role from public.profiles where id=auth.uid() and not is_anonymous;
  select activity_status into group_status from public.groups where id=coalesce(new.group_id,old.group_id);
  select edits_locked,activity_finalized into global_lock,finalized from public.classroom_settings where id=1;
  if user_role is distinct from 'teacher' and (global_lock or finalized or group_status='completed') then raise exception 'As edições desta atividade estão bloqueadas.'; end if;
  if tg_op='UPDATE' and user_role is distinct from 'teacher' and (old.is_locked or old.review_status in ('submitted','approved')) then raise exception 'Esta receita não está liberada para edição.'; end if;
  if tg_op='DELETE' and user_role is distinct from 'teacher' then raise exception 'Apenas o professor pode excluir receitas.'; end if;
  if tg_op in ('INSERT','UPDATE') then new.row_version=coalesce(old.row_version,0)+1; end if;
  return coalesce(new,old);
end $$;
revoke all on function public.guard_recipe_classroom() from public,anon,authenticated;

