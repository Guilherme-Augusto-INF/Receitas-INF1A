create or replace function public.set_classroom_control(p_action text)
returns public.classroom_settings language plpgsql security definer set search_path=''
as $$ declare result public.classroom_settings; begin
  perform private.require_teacher();
  if p_action='lock' then update public.classroom_settings set edits_locked=true where id=1 returning * into result;
  elsif p_action='unlock' then update public.classroom_settings set edits_locked=false,activity_finalized=false where id=1 returning * into result;
  elsif p_action='finalize' then update public.classroom_settings set edits_locked=true,activity_finalized=true where id=1 returning * into result; update public.recipes set is_locked=true where deleted_at is null;
  else raise exception 'Controle inválido.'; end if;
  perform private.log_activity('classroom_'||p_action,null,'classroom','1','{}'::jsonb);
  return result;
end $$;
revoke all on function public.set_classroom_control(text) from public,anon;
grant execute on function public.set_classroom_control(text) to authenticated;

create or replace function public.bulk_group_action(p_group_ids uuid[],p_action text)
returns integer language plpgsql security definer set search_path=''
as $$ declare affected integer; status_value text; begin
  perform private.require_teacher();
  if coalesce(array_length(p_group_ids,1),0)<1 or array_length(p_group_ids,1)>50 then raise exception 'Selecione entre 1 e 50 grupos.'; end if;
  if exists(select 1 from unnest(p_group_ids) id left join public.groups g on g.id=id where g.id is null) then raise exception 'A seleção contém grupo inválido.'; end if;
  if p_action like 'status:%' then
    status_value=split_part(p_action,':',2); if status_value not in ('not_started','in_progress','review','completed') then raise exception 'Status inválido.'; end if;
    update public.groups set activity_status=status_value,updated_at=now() where id=any(p_group_ids); get diagnostics affected=row_count;
    update public.recipes set is_locked=(status_value='completed'),updated_at=now() where group_id=any(p_group_ids) and deleted_at is null;
  elsif p_action in ('lock','unlock') then
    update public.recipes set is_locked=(p_action='lock'),updated_at=now() where group_id=any(p_group_ids) and deleted_at is null; get diagnostics affected=row_count;
  else raise exception 'Ação em massa inválida.'; end if;
  perform private.log_activity('groups_bulk_action',null,'groups',null,jsonb_build_object('action',p_action,'group_ids',p_group_ids,'affected',affected));
  return affected;
end $$;
revoke all on function public.bulk_group_action(uuid[],text) from public,anon;
grant execute on function public.bulk_group_action(uuid[],text) to authenticated;

create or replace function public.save_announcement(p_id uuid,p_title text,p_message text,p_published boolean,p_featured boolean,p_expires_at timestamptz)
returns public.announcements language plpgsql security definer set search_path=''
as $$ declare result public.announcements; begin
  perform private.require_teacher();
  if nullif(btrim(p_title),'') is null or length(btrim(p_title))>120 then raise exception 'Título inválido.'; end if;
  if nullif(btrim(p_message),'') is null or length(btrim(p_message))>2000 then raise exception 'Mensagem inválida.'; end if;
  if p_featured then update public.announcements set is_featured=false where deleted_at is null; end if;
  if p_id is null then insert into public.announcements(title,message,is_published,is_featured,expires_at,created_by,updated_by) values(btrim(p_title),btrim(p_message),p_published,p_featured,p_expires_at,auth.uid(),auth.uid()) returning * into result;
  else update public.announcements set title=btrim(p_title),message=btrim(p_message),is_published=p_published,is_featured=p_featured,expires_at=p_expires_at,updated_by=auth.uid(),updated_at=now() where id=p_id and deleted_at is null returning * into result; end if;
  if result.id is null then raise exception 'Aviso não encontrado.'; end if;
  update public.classroom_settings set announcement=(select message from public.announcements where deleted_at is null and is_published and (expires_at is null or expires_at>now()) order by is_featured desc,updated_at desc limit 1),announcement_updated_at=now(),updated_by=auth.uid() where id=1;
  perform private.log_activity('announcement_saved',null,'announcement',result.id::text,jsonb_build_object('published',result.is_published,'featured',result.is_featured));
  return result;
end $$;
revoke all on function public.save_announcement(uuid,text,text,boolean,boolean,timestamptz) from public,anon;
