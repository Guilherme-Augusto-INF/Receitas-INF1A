drop policy if exists recipe_reviews_authorized_read on public.recipe_reviews;
create policy recipe_reviews_authorized_read on public.recipe_reviews for select to authenticated
using (
  deleted_at is null and exists (
    select 1 from public.profiles viewer
    join public.recipes r on r.id=recipe_reviews.recipe_id
    where viewer.id=(select auth.uid()) and not viewer.is_anonymous
      and (viewer.role='teacher' or viewer.group_id=r.group_id)
  )
);

drop policy if exists group_checklist_authorized_read on public.group_checklist;
create policy group_checklist_authorized_read on public.group_checklist for select to authenticated
using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and not p.is_anonymous and (p.role='teacher' or p.group_id=group_checklist.group_id)));

drop policy if exists announcements_public_read on public.announcements;
create policy announcements_public_read on public.announcements for select to anon, authenticated
using (deleted_at is null and is_published and (expires_at is null or expires_at > now()));

-- Receitas excluídas não são expostas pelas consultas normais.
drop policy if exists "Anyone can view recipes" on public.recipes;
drop policy if exists recipes_public_read on public.recipes;
create policy recipes_public_read on public.recipes for select to anon, authenticated using (deleted_at is null);

