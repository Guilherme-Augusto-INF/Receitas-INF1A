create or replace function private.require_teacher() returns void
language plpgsql stable security definer set search_path=''
as $$ begin
  if auth.uid() is null or coalesce(((auth.jwt()->>'is_anonymous')::boolean),false)
     or not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='teacher' and not p.is_anonymous)
  then raise exception 'Apenas professores podem realizar esta ação.'; end if;
end $$;
revoke all on function private.require_teacher() from public,anon,authenticated;

