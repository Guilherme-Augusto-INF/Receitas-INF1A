create or replace function public.teacher_dashboard_snapshot()
returns jsonb language plpgsql stable security definer set search_path=''
as $$ declare result jsonb; begin
  perform private.require_teacher();
  select jsonb_build_object(
    'settings',(select to_jsonb(cs) from public.classroom_settings cs where cs.id=1),
    'metrics',jsonb_build_object(
      'students',(select count(*) from public.profiles where role='student' and not is_anonymous),
      'teachers',(select count(*) from public.profiles where role='teacher' and not is_anonymous),
      'groups',(select count(*) from public.groups),
      'recipes',(select count(*) from public.recipes where deleted_at is null),
      'students_without_group',(select count(*) from public.profiles where role='student' and not is_anonymous and group_id is null),
      'students_without_number',(select count(*) from public.profiles where role='student' and not is_anonymous and call_number is null),
      'groups_without_recipe',(select count(*) from public.groups g where not exists(select 1 from public.recipes r where r.group_id=g.id and r.deleted_at is null)),
      'review_waiting',(select count(*) from public.recipes where deleted_at is null and review_status='submitted')
    ),
    'profiles',(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'full_name',p.full_name,'role',p.role,'group_id',p.group_id,'call_number',p.call_number,'email',u.email,'created_at',p.created_at) order by p.full_name),'[]'::jsonb) from public.profiles p join auth.users u on u.id=p.id where not p.is_anonymous),
    'groups',(select coalesce(jsonb_agg(to_jsonb(g) order by g.slug),'[]'::jsonb) from public.groups g),
    'recipes',(select coalesce(jsonb_agg(to_jsonb(r) order by r.updated_at desc),'[]'::jsonb) from public.recipes r where r.deleted_at is null),
    'checklist',(select coalesce(jsonb_agg(to_jsonb(c) order by c.group_id,c.item_key),'[]'::jsonb) from public.group_checklist c),
    'announcements',(select coalesce(jsonb_agg(to_jsonb(a) order by a.updated_at desc),'[]'::jsonb) from public.announcements a where a.deleted_at is null),
    'trash',(select coalesce(jsonb_agg(to_jsonb(r) order by r.deleted_at desc),'[]'::jsonb) from public.recipes r where r.deleted_at is not null),
    'recent',(select coalesce(jsonb_agg(x order by (x->>'created_at')::timestamptz desc),'[]'::jsonb) from (select to_jsonb(h) x from public.activity_history h order by h.created_at desc limit 30) s)
  ) into result;
  return result;
end $$;
revoke all on function public.teacher_dashboard_snapshot() from public,anon;
grant execute on function public.teacher_dashboard_snapshot() to authenticated;

create or replace function public.manage_profile_extended(p_user_id uuid,p_name text,p_group_id uuid,p_call_number integer)
returns public.profiles language plpgsql security definer set search_path=''
as $$ declare result public.profiles; begin
  perform private.require_teacher();
  if nullif(btrim(p_name),'') is null or length(btrim(p_name))>120 then raise exception 'Informe um nome de até 120 caracteres.'; end if;
  if p_group_id is not null and not exists(select 1 from public.groups where id=p_group_id) then raise exception 'Grupo não encontrado.'; end if;
  if p_call_number is not null and p_call_number not between 1 and 999 then raise exception 'Número da chamada inválido.'; end if;
  update public.profiles set full_name=btrim(p_name),group_id=p_group_id,call_number=p_call_number,updated_at=now()
  where id=p_user_id and not is_anonymous returning * into result;
  if result.id is null then raise exception 'Usuário não encontrado.'; end if;
  perform private.log_activity('profile_updated',result.group_id,'profile',result.id::text,jsonb_build_object('name',result.full_name,'call_number',result.call_number));
  return result;
end $$;
revoke all on function public.manage_profile_extended(uuid,text,uuid,integer) from public,anon;
grant execute on function public.manage_profile_extended(uuid,text,uuid,integer) to authenticated;

create or replace function public.bulk_assign_students(p_user_ids uuid[],p_group_id uuid)
returns integer language plpgsql security definer set search_path=''
as $$ declare affected integer; begin
  perform private.require_teacher();
  if coalesce(array_length(p_user_ids,1),0)<1 or array_length(p_user_ids,1)>100 then raise exception 'Selecione entre 1 e 100 alunos.'; end if;
  if p_group_id is not null and not exists(select 1 from public.groups where id=p_group_id) then raise exception 'Grupo não encontrado.'; end if;
  if exists(select 1 from unnest(p_user_ids) id left join public.profiles p on p.id=id where p.id is null or p.role<>'student' or p.is_anonymous) then raise exception 'A seleção contém conta inválida.'; end if;
  update public.profiles set group_id=p_group_id,updated_at=now() where id=any(p_user_ids) and role='student' and not is_anonymous;
  get diagnostics affected=row_count;
  if affected<>array_length(p_user_ids,1) then raise exception 'A operação não pôde ser aplicada integralmente.'; end if;
  perform private.log_activity('students_bulk_moved',p_group_id,'profiles',null,jsonb_build_object('count',affected,'user_ids',p_user_ids));
  return affected;
end $$;
revoke all on function public.bulk_assign_students(uuid[],uuid) from public,anon;
grant execute on function public.bulk_assign_students(uuid[],uuid) to authenticated;

