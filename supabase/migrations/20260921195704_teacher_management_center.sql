create or replace function public.transition_recipe_review(p_recipe_id uuid,p_action text,p_message text default null)
returns public.recipes language plpgsql security definer set search_path=''
as $$ declare result public.recipes; actor public.profiles; settings public.classroom_settings; begin
  if auth.uid() is null or coalesce(((auth.jwt()->>'is_anonymous')::boolean),false) then raise exception 'Faça login para revisar receitas.'; end if;
  select * into actor from public.profiles where id=auth.uid() and not is_anonymous;
  select * into result from public.recipes where id=p_recipe_id and deleted_at is null for update;
  select * into settings from public.classroom_settings where id=1;
  if actor.id is null or result.id is null then raise exception 'Receita ou perfil não encontrado.'; end if;
  if p_action='submitted' then
    if actor.role<>'student' or actor.group_id is distinct from result.group_id then raise exception 'Você não pode enviar esta receita.'; end if;
    if settings.edits_locked or settings.activity_finalized or result.is_locked then raise exception 'As edições estão bloqueadas.'; end if;
    if result.review_status not in ('draft','changes_requested') then raise exception 'Esta receita não pode ser enviada agora.'; end if;
  elsif p_action in ('approved','changes_requested') then
    perform private.require_teacher();
    if result.review_status<>'submitted' then raise exception 'A receita precisa estar aguardando revisão.'; end if;
    if p_action='changes_requested' and nullif(btrim(p_message),'') is null then raise exception 'Explique a correção necessária.'; end if;
  else raise exception 'Transição inválida.'; end if;
  update public.recipes set review_status=p_action,is_locked=(p_action='approved'),row_version=row_version+1,updated_at=now(),updated_by=auth.uid() where id=p_recipe_id returning * into result;
  insert into public.recipe_reviews(recipe_id,author_id,event_type,message) values(p_recipe_id,auth.uid(),p_action,nullif(btrim(p_message),''));
  perform private.log_activity('recipe_'||p_action,result.group_id,'recipe',result.id::text,jsonb_build_object('title',result.title,'message',nullif(btrim(p_message),'')));
  return result;
end $$;
revoke all on function public.transition_recipe_review(uuid,text,text) from public,anon;
grant execute on function public.transition_recipe_review(uuid,text,text) to authenticated;

