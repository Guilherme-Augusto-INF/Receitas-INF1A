-- Central de gerenciamento do professor — evolução aditiva e sem perda de dados.
-- Compatível com o frontend estático no GitHub Pages.

alter table public.classroom_settings
  add column if not exists activity_name text not null default 'Atividade Prática de Biologia — INF1A',
  add column if not exists edits_locked boolean not null default false,
  add column if not exists activity_finalized boolean not null default false;

alter table public.recipes
  add column if not exists review_status text not null default 'draft',
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid references auth.users(id) on delete set null,
  add column if not exists row_version bigint not null default 1;

do $$ begin
  alter table public.recipes add constraint recipes_review_status_check
    check (review_status in ('draft','submitted','changes_requested','approved'));
exception when duplicate_object then null; end $$;

create table if not exists public.recipe_reviews (
  id bigint generated by default as identity primary key,
  recipe_id uuid not null references public.recipes(id) on delete cascade,
  author_id uuid references auth.users(id) on delete set null,
  event_type text not null check (event_type in ('submitted','comment','changes_requested','approved')),
  message text,
  created_at timestamptz not null default now(),
  deleted_at timestamptz,
  deleted_by uuid references auth.users(id) on delete set null,
  constraint recipe_reviews_message_length check (message is null or length(message) <= 2000)
);

create table if not exists public.group_checklist (
  group_id uuid not null references public.groups(id) on delete cascade,
  item_key text not null,
  label text not null,
  is_manual boolean not null default true,
  is_completed boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (group_id, item_key),
  constraint group_checklist_key_format check (item_key ~ '^[a-z0-9_]+$'),
  constraint group_checklist_label_length check (length(btrim(label)) between 1 and 120)
);

create table if not exists public.announcements (
  id uuid primary key default gen_random_uuid(),
  title text not null default 'Aviso do professor',
  message text not null,
  is_published boolean not null default true,
  is_featured boolean not null default false,
  expires_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint announcements_title_length check (length(btrim(title)) between 1 and 120),
  constraint announcements_message_length check (length(btrim(message)) between 1 and 2000)
);

alter table public.activity_history
  add column if not exists actor_role text,
  add column if not exists target_type text,
  add column if not exists target_id text;

create index if not exists recipes_review_status_idx on public.recipes(review_status) where deleted_at is null;
create index if not exists recipes_deleted_at_idx on public.recipes(deleted_at) where deleted_at is not null;
create index if not exists recipe_reviews_recipe_created_idx on public.recipe_reviews(recipe_id, created_at desc);
create index if not exists announcements_active_idx on public.announcements(is_published, is_featured, updated_at desc) where deleted_at is null;
create index if not exists activity_history_created_idx on public.activity_history(created_at desc);
create index if not exists activity_history_action_created_idx on public.activity_history(action, created_at desc);

insert into public.group_checklist(group_id,item_key,label,is_manual)
select g.id, v.item_key, v.label, v.is_manual
from public.groups g
cross join (values
 ('members_defined','Integrantes definidos',false),
 ('call_numbers','Números de chamada corretos',false),
 ('recipe_registered','Receita cadastrada',false),
 ('ingredients_filled','Ingredientes preenchidos',false),
 ('quantities_filled','Quantidades preenchidas',true),
 ('instructions_filled','Modo de preparo preenchido',false),
 ('recipe_reviewed','Receita revisada',false),
 ('teacher_approved','Aprovado pelo professor',false),
 ('ready_for_activity','Grupo pronto para atividade',true)
) v(item_key,label,is_manual)
on conflict (group_id,item_key) do nothing;

insert into public.announcements(message,is_published,is_featured,created_by,updated_by)
select cs.announcement,true,true,cs.updated_by,cs.updated_by
from public.classroom_settings cs
where cs.id=1 and nullif(btrim(cs.announcement),'') is not null
  and not exists(select 1 from public.announcements)
on conflict do nothing;

